const languageMeta = {
  en: { dir: "ltr", short: "EN", label: "English" },
  ckb: { dir: "rtl", short: "KU", label: "کوردی" },
  ar: { dir: "rtl", short: "AR", label: "العربية" }
};

const pageTitleKeys = {
  about: "pageTitleAbout",
  services: "pageTitleServices",
  pricing: "pageTitlePricing",
  emergency: "pageTitleEmergency",
  doctors: "doctorsPageTitle",
  contact: "pageTitleContact",
  privacy: "pageTitlePrivacy",
  index: "pageTitleIndex"
};

function getCurrentPageKey() {
  const path = window.location.pathname.toLowerCase();
  if (path.includes("privacy") || path.includes("legal") || path.includes("terms")) return "privacy";
  if (path.includes("about")) return "about";
  if (path.includes("service")) return "services";
  if (path.includes("pricing")) return "pricing";
  if (path.includes("emergency")) return "emergency";
  if (path.includes("doctor") || path.includes("specialist")) return "doctors";
  if (path.includes("contact")) return "contact";
  return "index";
}

let currentLanguage = localStorage.getItem("zhyanawa-language") || "en";
if (!languageMeta[currentLanguage]) currentLanguage = "en";

function t(key) {
  return translations[currentLanguage]?.[key] ?? translations.en[key] ?? key;
}

function applyLanguage(lang) {
  if (!languageMeta[lang]) return;
  currentLanguage = lang;
  localStorage.setItem("zhyanawa-language", lang);

  document.documentElement.lang = lang;
  document.documentElement.dir = languageMeta[lang].dir;

  // Update dynamic page title
  const pageKey = getCurrentPageKey();
  const titleKey = pageTitleKeys[pageKey] || "pageTitleIndex";
  const localizedTitle = t(titleKey);
  if (localizedTitle) {
    document.title = localizedTitle;
  }

  // Update text elements
  const currentYear = new Date().getFullYear();
  const kurdishYear = String(currentYear).replace(/\d/g, (d) => "٠١٢٣٤٥٦٧٨٩"[d]);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    let value = t(key);
    if (key === "footerCopyright") {
      const yearStr = lang === "ckb" ? kurdishYear : String(currentYear);
      value = value.replace("{year}", yearStr);
    }
    if (value) el.textContent = value;
  });

  // Update placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    const value = t(key);
    if (value) el.placeholder = value;
  });

  // Update language trigger button
  const langShort = document.getElementById("current-lang-code");
  if (langShort) langShort.textContent = languageMeta[lang].short;

  const shortLabels = document.querySelectorAll("[data-lang-short]");
  shortLabels.forEach((el) => {
    el.textContent = languageMeta[lang].short;
  });

  // Update active state in dropdown
  document.querySelectorAll(".lang-option-btn").forEach((btn) => {
    const isSelected = btn.dataset.lang === lang;
    btn.classList.toggle("is-selected", isSelected);
    btn.setAttribute("aria-selected", String(isSelected));
  });

  document.dispatchEvent(new CustomEvent("languagechange", { detail: { language: lang } }));
}

function formatNumber(num) {
  if (currentLanguage === "ckb" || currentLanguage === "ar") {
    const easternDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    return String(num).replace(/\d/g, (d) => easternDigits[d]);
  }
  return String(num);
}

window.zhyanawaI18n = {
  formatNumber,
  t,
  applyLanguage,
  get language() { return currentLanguage; },
  languageMeta,
  translations
};
